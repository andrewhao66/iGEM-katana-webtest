"""
kg_refs.py — Kagami reference part set (PUBLIC parts only).

The set is loaded from a bundled data file (refs/reference_parts.tsv +
reference_parts.fasta), which is generated by build_refs.py — mostly a projection
of the *verified, sealed* public reference parts in the Synbio parts-library, plus
a few hand-seeded canonical parts. Each entry carries a `provenance` string:
  - "parts-library <source>"  → sequence came from a sealed, LOCK-verified library
    part (primary-sourced, hash-checked). Trustworthy.
  - "seed — verify vs ..."     → hand-seeded canonical public sequence still to be
    confirmed against its primary source. Kagami surfaces this tag.

IP boundary: PUBLIC reference parts only (Anderson promoters, standard RBS/
terminators, common reporters/markers/oris, public inducible promoters). No
`designed` or otherwise non-public sequences are included. Kagami ships under the
WIST iGEM team on this basis. To expand, re-run build_refs.py (never paste a
sequence out of a construct you are auditing — circular provenance).
"""
import os
import sys

_DIR = os.path.dirname(os.path.abspath(__file__))
_FASTA = os.path.join(_DIR, "refs", "reference_parts.fasta")
_TSV = os.path.join(_DIR, "refs", "reference_parts.tsv")
_GENOMES = os.path.join(_DIR, "genomes")

def _import_core():
    """core/ lives at the repository root, one level above kagami/.

    Kagami deliberately imports NOTHING from the forward ENGINE and drives it as
    subprocesses instead, so the two stay decoupled. core/ is a different thing: not the
    engine, but the shared definition of what a manifest and a part file ARE. Four
    Kagami modules each had their own copy of that, and the point of core/ is that there
    is one.

    Returns (hashing, lock, parts), or (None, None, None) when core/ is absent -- Kagami
    unzipped on its own must keep working, because it is the tool the wiki invites a
    stranger to download.
    """
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    if os.path.isdir(os.path.join(root, "core")) and root not in sys.path:
        sys.path.insert(0, root)
    try:
        from core import hashing, lock, parts
        return hashing, lock, parts
    except ImportError:
        return None, None, None


_hashing, _lock, _core_parts = _import_core()

